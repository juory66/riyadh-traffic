# الأيام
days = ["الأحد", "الاثنين", "الثلاثاء", "الأربعاء", "الخميس", "الجمعة", "السبت"]

# الساعات
hours = list(range(0, 24))

# ==============================
# دالة مستوى الازدحام
# ==============================
def get_congestion(hour, day, district):
    """
    تحسب مستوى الازدحام (0-10) بناءً على:
    - الساعة
    - اليوم
    - الحي
    """
    base = 2.0

    # ازدحام عالي — ساعات النهار الكاملة (8 صباحاً — 6 مساءً)
    if 8 <= hour <= 18:
        base += 5.5
        # ذروة الدخول (8-9 صباحاً)
        if 8 <= hour <= 9:
            base += 1.5
        # ذروة منتصف النهار (12-1 ظهراً)
        elif 12 <= hour <= 13:
            base += 0.5
        # ذروة الخروج (4-6 مساءً)
        elif 16 <= hour <= 18:
            base += 1.5
    # متوسط — بعد الدوام (7-8 مساءً)
    elif 19 <= hour <= 20:
        base += 2.5
    # منخفض — ليل ومبكر (9 مساءً — 7 صباحاً)
    elif hour >= 21 or hour <= 7:
        base -= 1.5

    # تعديل حسب اليوم
    if day in ["الجمعة", "السبت"]:
        base -= 1.5  # عطلة نهاية الأسبوع
    elif day == "الخميس":
        base += 0.5  # قبل العطلة

    # تعديل حسب الحي
    busy_districts = ["طريق الملك فهد", "العليا", "الدائري الشمالي", "طريق الملك عبدالله", "طريق العروبة", "السليمانية", "طريق الدمام"]
    quiet_districts = ["الرحمانية", "العرضة", "الدائري الجنوبي", "الشفا", "المصانع", "الجزيرة"]

    if district in busy_districts:
        base += 1.5
    elif district in quiet_districts:
        base -= 1.0

    # إضافة ضوضاء عشوائية
    noise = np.random.normal(0, 0.5)
    base += noise

    # تحديد النطاق بين 0 و 10
    return round(min(max(base, 0), 10), 2)


def get_congestion_label(level):
    if level <= 3:
        return "منخفض"
    elif level <= 6:
        return "متوسط"
    else:
        return "مرتفع"


# ==============================
# توليد البيانات
# ==============================
records = []

# توليد بيانات لمدة 90 يوماً
start_date = pd.Timestamp("2024-01-01")

for day_offset in range(90):
    current_date = start_date + pd.Timedelta(days=day_offset)
    day_name = days[current_date.dayofweek % 7]

    for hour in hours:
        for district, (lat, lon) in districts.items():
            congestion_level = get_congestion(hour, day_name, district)
            congestion_label = get_congestion_label(congestion_level)

            # سرعة المرور (عكسية للازدحام)
            speed = round(max(10, 120 - (congestion_level * 10) + np.random.normal(0, 3)), 1)

            records.append({
                "التاريخ":          current_date.strftime("%Y-%m-%d"),
                "اليوم":            day_name,
                "الساعة":           hour,
                "الحي":             district,
                "خط_العرض":         lat + np.random.uniform(-0.005, 0.005),
                "خط_الطول":         lon + np.random.uniform(-0.005, 0.005),
                "مستوى_الازدحام":   congestion_level,
                "تصنيف_الازدحام":   congestion_label,
                "السرعة_كم_ساعة":   speed,
            })

df = pd.DataFrame(records)

